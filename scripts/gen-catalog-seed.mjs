// Regenerates supabase/migrations/0004_seed_coffee_catalog.sql from the scraped
// roastery JSON under data/roasteries/*.json (Phase 3 feature #3, Decision #67).
//
// Run from the repo root:  node scripts/gen-catalog-seed.mjs
//
// Rerun manually whenever new roasteries are scraped into data/roasteries/ —
// there is no in-app import (PRD §13.2). The seed upserts into coffee_catalog;
// a scraped row replaces a matching (case-insensitive brand+name) user row.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = 'data/roasteries'
const OUT = 'supabase/migrations/0004_seed_coffee_catalog.sql'
const files = readdirSync(ROOT).filter((f) => f.endsWith('.json')).sort()

// Non-single-bag products we never want in a bean picker.
const NONCOFFEE_RE = /\b(sampler|explorer pack|trio pack|gift|hamper|bundle|box of|pack of|combo|capsule|nespresso|instant|sachet|drip kit|drip bag|drip bags|cold brew bag|starter kit|subscription|gift card)\b/i
// Content catch for drip-bag/sachet kits whose NAME reads like whole beans.
const NONBEAN_NOTES_RE = /not whole bean|drip[\s-]?bag|sachet|single[\s-]serve/i

// Collapse a roaster's free-text roast label into the app's 5 canonical buckets
// (null when unmappable/green — the Add-Bean roast-level dropdown accepts null).
function bucketRoast(raw) {
  if (!raw) return null
  const s = String(raw).trim().toLowerCase()
  if (/green|unroasted/.test(s)) return null
  if (/medium[\s-]*dark/.test(s)) return 'Medium-Dark'
  if (/medium[\s-]*light/.test(s)) return 'Medium-Light'
  if (/full city|higher-degree|\bespresso\b/.test(s)) return 'Medium-Dark'
  if (/\bdark\b|french|italian|vienna/.test(s)) return 'Dark'
  if (/filter roast|blonde|cinnamon|\blight\b/.test(s)) return 'Light'
  if (/\bmedium\b/.test(s)) return 'Medium'
  return null
}

const q = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).trim().replace(/'/g, "''")}'`)
const jsonb = (v) => (v == null ? 'NULL' : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`)
const numOrNull = (v) => (v == null || Number.isNaN(Number(v)) ? 'NULL' : Number(v))

const rows = []
let excluded = 0, roastMapped = 0, roastNull = 0
for (const f of files) {
  const data = JSON.parse(readFileSync(join(ROOT, f), 'utf8'))
  const roastery = data.roastery || f.replace('.json', '')
  for (const c of data.coffees || []) {
    const name = (c.name || '').trim()
    if (!name) { excluded++; continue }
    if (c.bundle === true || NONCOFFEE_RE.test(name)) { excluded++; continue }
    if (c.tastingNotes && NONBEAN_NOTES_RE.test(c.tastingNotes)) { excluded++; continue }
    if (c.fetchError) { excluded++; continue }
    const roast = bucketRoast(c.roastLevel)
    if (roast) roastMapped++; else roastNull++
    const weights = (c.variants || []).map((v) => v.weightGrams).filter((w) => w != null && w > 0)
    const lastAmount = weights.length ? Math.min(...weights) : 250 // smallest retail bag; 250g default
    const o = c.origin || {}
    rows.push({
      brand: roastery, coffee_name: name, roastery,
      origin_country: o.country ?? null, origin_region: o.region ?? null, origin_estate: o.estate ?? null,
      altitude: o.altitude ?? null, variety: c.variety ?? null, process: c.process ?? null,
      roast_level: roast, tasting_notes: c.tastingNotes ?? null,
      variants: c.variants && c.variants.length ? c.variants : null,
      availability: c.availability ?? null, source_url: c.productUrl ?? null, last_amount_g: lastAmount,
    })
  }
}

const cols = ['brand', 'coffee_name', 'roastery', 'origin_country', 'origin_region', 'origin_estate', 'altitude', 'variety', 'process', 'roast_level', 'tasting_notes', 'variants', 'availability', 'source_url', 'last_amount_g', 'source']
const lines = []
lines.push('-- Coffee Brewing Calculator — Phase 3 Feature #3 seed (Decision #67).')
lines.push('-- GENERATED by scripts/gen-catalog-seed.mjs from data/roasteries/*.json — do not edit by hand.')
lines.push('-- Idempotent: re-running refreshes each row. Per §13.2 a scraped row REPLACES a matching')
lines.push("-- (case-insensitive brand+name) user row — ON CONFLICT sets source='scraped'.")
lines.push(`-- ${rows.length} single coffees (bundles/samplers/instant/drip-kits excluded). Run after 0003_coffee_repository_enrichment.sql.`)
lines.push('')
lines.push(`insert into public.coffee_catalog (${cols.join(', ')}) values`)
const valueRows = rows.map((r) => {
  const vals = [
    q(r.brand), q(r.coffee_name), q(r.roastery), q(r.origin_country), q(r.origin_region), q(r.origin_estate),
    q(r.altitude), q(r.variety), q(r.process), q(r.roast_level), q(r.tasting_notes), jsonb(r.variants),
    q(r.availability), q(r.source_url), numOrNull(r.last_amount_g), `'scraped'`,
  ]
  return `  (${vals.join(', ')})`
})
lines.push(valueRows.join(',\n'))
lines.push('on conflict (lower(brand), lower(coffee_name)) do update set')
lines.push([
  'roastery', 'origin_country', 'origin_region', 'origin_estate', 'altitude', 'variety', 'process',
  'roast_level', 'tasting_notes', 'variants', 'availability', 'source_url', 'last_amount_g',
].map((c) => `  ${c} = excluded.${c}`).join(',\n') + ',')
lines.push("  source = 'scraped',")
lines.push('  updated_at = now();')
lines.push('')
writeFileSync(OUT, lines.join('\n'), 'utf8')

console.log(`Wrote ${rows.length} rows to ${OUT}`)
console.log(`Excluded (bundles/non-coffee/drip-kits/empty/fetchError): ${excluded}`)
console.log(`Roast level: mapped=${roastMapped}  null=${roastNull}`)
