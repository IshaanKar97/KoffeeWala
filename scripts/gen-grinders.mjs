// Generates src/lib/grinders.scraped.js — the curated subset of scraped grinders
// (Phase 3 feature #3). Only grinders that carry BOTH a max-click count and a
// max-micron span are usable by the app's click-based model; the rest (stepless
// / electric with no clicks) are skipped. Deduped against the hand-curated seed.
//
// Run from repo root:  node scripts/gen-grinders.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'data/grinders/honestcoffeeguide-grinders.json'
const OUT = 'src/lib/grinders.scraped.js'
const MICRON_MAX = 1400

// The 8 hand-tuned grinders already in SEED_GRINDERS — never override these.
const CURATED = new Set([
  'timemore c3s', 'timemore c3', 'timemore c3 esp', 'timemore c2', 'timemore c5',
  'comandante c40 mk4', 'comandante c60 baracuda', 'comandante x25 trailmaster',
].map((s) => s.replace(/\s+/g, ' ').trim().toLowerCase()))

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const data = JSON.parse(readFileSync(SRC, 'utf8'))
const out = []
const seenIds = new Set()
let skippedNoClicks = 0, skippedDupe = 0

for (const g of data.grinders || []) {
  const clicks = g.maxClicks
  const microns = Math.min(g.maxMicrons ?? 0, MICRON_MAX)
  if (!(clicks > 0) || !(microns > 0)) { skippedNoClicks++; continue }
  const key = `${g.brand} ${g.model}`.replace(/\s+/g, ' ').trim().toLowerCase()
  if (CURATED.has(key)) { skippedDupe++; continue }
  const id = `hcg-${slug(`${g.brand}-${g.model}`)}`
  if (seenIds.has(id)) { skippedDupe++; continue }
  seenIds.add(id)
  out.push({
    id,
    brand: g.brand,
    model: g.model,
    clicks: Math.round(clicks),
    umPerClick: Math.round((microns / clicks) * 10) / 10,
    scraped: true,
  })
}
out.sort((a, b) => (a.brand === b.brand ? a.model.localeCompare(b.model) : a.brand.localeCompare(b.brand)))

const body = `// GENERATED by scripts/gen-grinders.mjs from ${SRC} — do not edit by hand.
// Curated subset (Phase 3 feature #3): scraped grinders that carry both a
// max-click count and a micron span, so the click-based model can derive
// µm/click. Stepless/no-click grinders and the hand-tuned seed are excluded.
export const SCRAPED_GRINDERS = ${JSON.stringify(out, null, 2)}
`
writeFileSync(OUT, body, 'utf8')
console.log(`Wrote ${out.length} grinders to ${OUT}`)
console.log(`Skipped: no clicks/microns=${skippedNoClicks}  dupe/curated=${skippedDupe}`)
const byBrand = {}
for (const g of out) byBrand[g.brand] = (byBrand[g.brand] || 0) + 1
console.log('Brands:', Object.entries(byBrand).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}=${v}`).join(', '))
